function Get-Text([string]$Key, [object[]]$Values = @()) {
    if (-not $script:Messages.ContainsKey($script:Language) -or -not $script:Messages[$script:Language].ContainsKey($Key)) {
        throw "Unknown interface language/key: $script:Language/$Key"
    }
    return [string]::Format($script:Messages[$script:Language][$Key], $Values)
}
