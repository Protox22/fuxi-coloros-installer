#!/usr/bin/env python3
"""Generate dependency-free PowerShell/Bash translations from one catalog."""
import argparse
import json
from pathlib import Path
import shlex

ROOT = Path(__file__).resolve().parent.parent


def render():
    messages = json.loads((ROOT / 'tools/messages.json').read_text(encoding='utf-8'))
    keys = set(messages['en'])
    assert set(messages) == {'ru', 'en', 'pl'}
    ps = ["# Generated by tools/generate_messages.py; edit tools/messages.json.",
          "if (-not (Test-Path Variable:Language)) { $Language = 'ru' }", '$script:Messages = @{']
    sh = ['# Generated by tools/generate_messages.py; edit tools/messages.json.',
          'LANGUAGE="${LANGUAGE:-ru}"', 'get_text() {', '    local key="$1" value argument index=0 token',
          '    shift', '    case "$LANGUAGE:$key" in']
    for language in ('ru', 'en', 'pl'):
        assert set(messages[language]) == keys, language
        ps.append(f"    '{language}' = @{{")
        for key, value in sorted(messages[language].items()):
            assert '\n' not in value
            ps.append("        '%s' = '%s'" % (key, value.replace("'", "''")))
            sh.append('        %s:%s) value=%s ;;' % (language, key, shlex.quote(value)))
        ps.append('    }')
    ps += ['}', '''function Get-Text([string]$Key, [object[]]$Values = @()) {
    if (-not $script:Messages.ContainsKey($script:Language) -or -not $script:Messages[$script:Language].ContainsKey($Key)) {
        throw "Unknown interface language/key: $script:Language/$Key"
    }
    return [string]::Format($script:Messages[$script:Language][$Key], $Values)
}''']
    sh += ['        *) printf "Unknown interface language/key: %s/%s\\n" "$LANGUAGE" "$key" >&2; return 1 ;;',
           '    esac', '    for argument in "$@"; do', '        token="{$index}"',
           '        value="${value//"$token"/"$argument"}"', '        index=$((index + 1))',
           '    done', '    printf "%s\\n" "$value"', '}']
    return {'installer/scripts/language.ps1': b'\xef\xbb\xbf' + ('\n'.join(ps) + '\n').encode(),
            'installer/scripts/language.sh': ('\n'.join(sh) + '\n').encode()}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, data in render().items():
        path = ROOT / name
        if args.check:
            assert path.read_bytes() == data, 'Regenerate ' + name
        else:
            path.write_bytes(data)
